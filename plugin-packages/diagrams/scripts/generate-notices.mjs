import fs from 'node:fs';
import path from 'node:path';

const root=path.resolve(import.meta.dirname,'..');
function resolvePackage(name,from) {
  for(let directory=from;;directory=path.dirname(directory)) {
    const candidate=path.join(directory,'node_modules',name,'package.json');
    if(fs.existsSync(candidate))return candidate;
    if(path.dirname(directory)===directory)throw new Error(`Installed package missing: ${name}`);
  }
}
const packages=new Map();
const pending=['mermaid','@dagrejs/dagre','ajv','playwright'].map(name=>resolvePackage(name,root));
while(pending.length) {
  const file=pending.pop(),metadata=JSON.parse(fs.readFileSync(file,'utf8'));
  const key=`${metadata.name}@${metadata.version}`;
  if(packages.has(key))continue;
  const directory=path.dirname(file);
  const licenses=fs.readdirSync(directory).filter(name=>/^(licen[sc]e|copying|notice)(\.|$)/i.test(name)&&fs.statSync(path.join(directory,name)).isFile());
  let licenseText=licenses.map(name=>`### ${name}\n\n${fs.readFileSync(path.join(directory,name),'utf8').trim()}`).join('\n\n');
  if(!licenses.length) {
    const readme=path.join(directory,'README.md');
    const section=fs.existsSync(readme)?fs.readFileSync(readme,'utf8').match(/^## License\s*\n([\s\S]*?)(?=^## |$(?![\s\S]))/m)?.[1]:undefined;
    if(!section||!section.includes('Permission is hereby granted'))throw new Error(`No complete license text found for ${key}`);
    licenseText=`### README.md — License\n\n${section.trim()}`;
  }
  packages.set(key,{metadata,text:licenseText});
  for(const dependency of Object.keys(metadata.dependencies??{}))pending.push(resolvePackage(dependency,directory));
}
const sorted=[...packages].sort(([a],[b])=>a<b?-1:a>b?1:0);
const text=`# Third-party notices\n\nGenerated by scripts/generate-notices.mjs from the pinned installed dependency closure.\nMermaid, Dagre and Ajv are bundled; Playwright is an external runtime dependency.\n\n| Package | Version | License |\n|---|---|---|\n${sorted.map(([,entry])=>`| \`${entry.metadata.name}\` | ${entry.metadata.version} | ${entry.metadata.license} |`).join('\n')}\n\n${sorted.map(([key,entry])=>`## ${key}\n\n${entry.text}`).join('\n\n')}\n`.replaceAll('\r\n','\n');
const target=path.join(root,'THIRD_PARTY_NOTICES.md');
if(process.argv.includes('--check')) {
  if(!fs.existsSync(target)||fs.readFileSync(target,'utf8').replaceAll('\r\n','\n')!==text)throw new Error('Diagrams third-party notices are stale. Run its generate:notices command.');
} else fs.writeFileSync(target,text);
