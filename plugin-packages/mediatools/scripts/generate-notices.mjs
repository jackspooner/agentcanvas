import fs from 'node:fs';
import path from 'node:path';
import { createHash } from 'node:crypto';

const root = path.resolve(import.meta.dirname, '..');
const firstPartyPackages = new Set([
  'media-tools-mcp',
  '@workspace2/media-contracts',
  '@workspace2/media-io',
  '@workspace2/router-clients',
  '@workspace2/router-contracts',
  '@workspace2/runtime-contracts'
]);
const licenseDirectory = path.join(root, 'licenses');
const licenseFallbacks = JSON.parse(fs.readFileSync(path.join(licenseDirectory, 'manifest.json'), 'utf8'));

function fallbackLicense(identity, declaredLicense) {
  const fallback = licenseFallbacks[identity];
  if (!fallback || fallback.declaredLicense !== declaredLicense) {
    throw new Error(`No complete license text found for ${identity}`);
  }
  const text = fs.readFileSync(path.join(licenseDirectory, fallback.file), 'utf8');
  if (createHash('sha256').update(text).digest('hex') !== fallback.sha256) {
    throw new Error(`License fallback checksum mismatch for ${identity}`);
  }
  return `### Upstream license — ${fallback.textLicense}\n\nSource: ${fallback.source}\n\n${fallback.note}\n\n${text.trim()}`;
}

export async function generateNotices(packageJsonFiles, check = false) {
  const packages = new Map();
  for (const file of packageJsonFiles) {
    const metadata = JSON.parse(fs.readFileSync(file, 'utf8'));
    const identity = `${metadata.name ?? 'unknown'}@${metadata.version ?? 'unknown'}`;
    if (!metadata.license && !firstPartyPackages.has(metadata.name)) {
      throw new Error(`Missing license metadata for bundled third-party dependency ${identity} in ${file}`);
    }
    if (packages.has(identity)) continue;
    const directory = path.dirname(file);
    const licenseFiles = fs.readdirSync(directory).filter((name) =>
      /^(licen[sc]e|copying|notice)(\.|$)/i.test(name) && fs.statSync(path.join(directory, name)).isFile()
    ).sort();
    let licenseText = licenseFiles
      .map((name) => `### ${name}\n\n${fs.readFileSync(path.join(directory, name), 'utf8').trim()}`)
      .join('\n\n');
    if (!licenseFiles.length && metadata.license) {
      const readme = path.join(directory, 'README.md');
      const section = fs.existsSync(readme)
        ? fs.readFileSync(readme, 'utf8').match(/^## License\s*\n([\s\S]*?)(?=^## |$(?![\s\S]))/m)?.[1]
        : undefined;
      licenseText = section?.includes('Permission is hereby granted')
        ? `### README.md — License\n\n${section.trim()}`
        : fallbackLicense(identity, metadata.license);
    }
    packages.set(identity, {
      metadata,
      license: metadata.license ?? 'License not declared',
      text: metadata.license
        ? licenseText
        : 'Pinned Workspace2 first-party package. No license is declared in its package metadata or package files.'
    });
  }

  const sorted = [...packages].sort(([left], [right]) => left.localeCompare(right));
  const content = `# Third-party notices\n\nGenerated by scripts/generate-notices.mjs from the package modules included in the MediaTools server bundle.\n\n| Package | Version | License |\n|---|---|---|\n${sorted.map(([, entry]) => `| \`${entry.metadata.name}\` | ${entry.metadata.version} | ${entry.license} |`).join('\n')}\n\n${sorted.map(([identity, entry]) => `## ${identity}\n\n${entry.text}`).join('\n\n')}\n`.replaceAll('\r\n', '\n');
  const target = path.join(root, 'THIRD_PARTY_NOTICES.md');
  if (check) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8').replaceAll('\r\n', '\n') !== content) {
      throw new Error('MediaTools third-party notices are stale. Run its generate:notices command.');
    }
  } else {
    fs.writeFileSync(target, content);
  }
}
